"""Generate reports/MANUSCRIPT_SUMMARY.md, a manuscript-style account of Task A.

The same numbers as `reports/FINAL_REPORT.md`, in the register a methods paper would use:
abstract, background, methods, results, discussion, limitations. The final report is
organised for someone auditing the work; this is organised for someone reading it.

Numbers are read from the result files rather than typed, for the same reason as
everywhere else in this repository: a hand-copied figure eventually disagrees with the
file it came from.

    python reports/build_manuscript_summary.py

Output: reports/MANUSCRIPT_SUMMARY.md
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))
sys.path.insert(0, str(REPO_ROOT / "bench"))

from schemas.task_schema import print_run_header, sha256_of  # noqa: E402

CURATED = REPO_ROOT / "tasks" / "taskA_crossfamily" / "curated.csv"
MAIN = REPO_ROOT / "bench" / "results" / "taskA_representations.json"
VALIDATION = REPO_ROOT / "bench" / "results" / "taskA_validation.json"
OUT = REPO_ROOT / "reports" / "MANUSCRIPT_SUMMARY.md"

CLS_EPSILON = 0.01


def main() -> int:
    print_run_header("reports/build_manuscript_summary.py", [CURATED, MAIN, VALIDATION])
    with CURATED.open(encoding="utf-8") as handle:
        rows = list(csv.DictReader(handle))
    main_results = json.loads(MAIN.read_text(encoding="utf-8"))
    validation = json.loads(VALIDATION.read_text(encoding="utf-8"))
    results = main_results["results"]
    noise = validation["noise"]
    permutation = validation["permutation"]
    intervals = validation["intervals"]
    matched = validation["search_null_matched"]

    active = np.array([r["active"] == "1" for r in rows])
    prevalence = float(active.mean())
    efficiency = np.array([float(r["pe_efficiency_pct"]) for r in rows])
    weights = efficiency + CLS_EPSILON
    kish = float(weights.sum() ** 2 / np.square(weights).sum())
    families = Counter(r["family"] for r in rows)
    zero_active = sorted(
        f
        for f in families
        if not any(r["family"] == f and r["active"] == "1" for r in rows)
    )

    from validate_taskA import minimum_resolvable_difference

    mrd = minimum_resolvable_difference(validation["pairwise"])

    def pr(label: str) -> float:
        return results[label]["classification"]["pr_auc"]

    def noise_pr(label: str) -> float | None:
        return noise.get(label, {}).get("classification", {}).get("pr_auc")

    def perm_pr(label: str) -> float | None:
        return permutation.get(label, {}).get("classification", {}).get("pr_auc_p95")

    survivors = [
        label
        for label in results
        if "classification" in results[label]
        and noise_pr(label) is not None
        and perm_pr(label) is not None
        and pr(label) > max(noise_pr(label), prevalence, perm_pr(label))
    ]
    best_cls = max(
        e[h]["cls"] for e in results.values() for h in main_results["heads"] if h in e
    )
    esm_labels = [k for k in results if k.startswith("esm2_")]

    lines = [
        "# Protein language model embeddings do not transfer to cross-family reverse transcriptase activity",
        "",
        "A manuscript-style summary of Task A. Generated by",
        "`reports/build_manuscript_summary.py`; every number is read from the result file",
        "that produced it. The auditable version of the same work, organised by phase, is",
        "[FINAL_REPORT.md](FINAL_REPORT.md).",
        "",
        "## Abstract",
        "",
        "Protein language models are widely used as general-purpose protein",
        "representations, and they perform well on within-protein variant effect",
        "prediction. Whether they transfer to cross-family functional prediction, where a",
        "model must generalise to an evolutionary lineage it has not seen labelled, is a",
        "separate question. We tested it on a published panel built for it: the",
        str(len(rows))
        + " reverse transcriptases Doman et al. assayed as prime editors across "
        + str(len(families))
        + " families,",
        "of which " + str(int(active.sum())) + " show detectable activity.",
        "",
        "We benchmarked 12 representations, including ESM-2 at four parameter scales,",
        "through a nested leave-one-family-out protocol with two fixed model heads and a",
        "single selected hyperparameter, and compared every score against three controls: a",
        "dimensionality-matched Gaussian noise control, a search-capacity null at matched",
        "free-parameter count, and a label permutation.",
        "",
        "**No ESM-2 representation survives.** Embeddings at 8M and 650M parameters exceed",
        "their Gaussian noise controls and then fail label permutation, their observed",
        "precision-recall area falling below the 95th percentile of what the same pipeline",
        "achieves on shuffled labels. The only representation that survives all three",
        "controls is a 4-mer frequency block, and its signal is strongly associated with",
        "sequence length and family structure rather than with any specific sequence motif.",
        "No representation under either head clears the composite metric the panel's source",
        "competition used.",
        "",
        "The same ESM-2 650M representation classifies reverse transcriptase family at",
        "0.8197 five-fold accuracy against a 0.3214 majority baseline, and its leading",
        "principal component tracks sequence length at Spearman -0.7681. We conclude that",
        "mean-pooled ESM-2 embeddings of these sequences encode lineage and length, and that",
        "this does not convert into cross-family activity prediction on a panel of this size.",
        "",
        "## Background",
        "",
        "Prime editing fuses a Cas9 nickase to a reverse transcriptase, and the choice of",
        "reverse transcriptase determines both the editor's size and its efficiency. Doman",
        "et al. surveyed reverse transcriptases from diverse phylogenetic origins as prime",
        "editors in HEK293T cells, which makes their panel the natural testbed for whether a",
        "sequence representation can predict prime editing competence in an unseen lineage.",
        "",
        "The panel is small and its families are unbalanced, so the question is as much",
        "about what such a panel can resolve as about what the representations encode. Both",
        "are addressed here.",
        "",
        "## Methods",
        "",
        "### Dataset",
        "",
        "Supplementary Table S1 of Doman et al. (DOI `10.1016/j.cell.2023.07.039`, PMC",
        "accession PMC10482982, CC BY 4.0) was retrieved programmatically and is committed",
        "with its checksum. The workbook holds one sheet containing two caption-delimited",
        "FASTA blocks under a single running index: "
        + str(len(rows))
        + " assayed enzymes, and 486 further",
        "sequences used only for the paper's phylogenetic analysis. Activity is encoded as a",
        "green cell fill rather than as a column, so it is invisible to any reader that",
        "parses values alone.",
        "",
        "Only the assayed block enters the benchmark. The parser asserts the block captions,",
        "the entry count, the fill count and the index range before reading any data row,",
        "and halts rather than adapting if the source changes.",
        "",
        "All "
        + str(len(rows))
        + " sequences are byte-identical by SHA256 to the inherited dataset this work",
        "rebuilds, and the inherited length column agrees with every sequence length.",
        "",
        "### Labels, and one material caveat",
        "",
        "The binary activity label is read directly from the fill and is reproducible from",
        "the source file. The continuous efficiency label is not. **Table S1 contains no",
        "numeric cell except the row index, and none of the six supplementary workbooks",
        "carries the per-enzyme survey efficiencies.** The values in use are attributable to",
        "Figure S1A, whose caption gives the assay as HEK293T, HEK3 +5 G to T, mean of three",
        "replicates. Every non-zero value is an exact multiple of 0.5 and every inactive is",
        "exactly 0.0, which is the signature of a plot read by eye rather than a table",
        "transcribed. Classification is therefore the primary analysis and every result",
        "derived from the efficiency column is reported with this provenance attached.",
        "",
        "### Evaluation",
        "",
        "Nested leave-one-family-out, one fold per family. The inner loop receives training",
        "families only, and a positive control that deliberately leaks held-out labels is",
        "required to fail, which it does. Splits are frozen files, verified free of",
        "sequence, family and cluster leakage, and asserted to reproduce the partition the",
        "harness derives at run time.",
        "",
        "Identity clustering with MMseqs2 at 90, 70, 50 and 30 percent identity. No cluster",
        "crosses a family boundary above 50 percent. Four do at 30 percent, so the design",
        "holds out a clade but not remote homology, and that is reported as a limitation",
        "rather than claimed as control.",
        "",
        "### Representations and heads",
        "",
        "Twelve representations: sequence length alone; amino acid, dipeptide, 3-mer and",
        "4-mer composition; physicochemical descriptors; a combined handcrafted block",
        "including structural features; ESM-2 at 8M, 35M, 150M and 650M parameters, final",
        "layer, mean pooled over residue positions; and the handcrafted block concatenated",
        "with ESM-2 650M.",
        "",
        "Two model heads and no others: regularized logistic regression for the binary",
        "label and ridge regression for the continuous one. The only selected quantity is",
        "the regularization strength, one free parameter from a grid of six fixed in",
        "advance. Scaling and imputation are pipeline steps fitted on training rows alone.",
        "",
        "This restriction is deliberate. The capacity to search over model families is",
        "itself a source of score: on this panel and this metric, a search with fifty free",
        "parameters reaches 0.9727 on pure Gaussian noise. Holding the head fixed is also",
        "what makes a representation comparison interpretable, since otherwise a difference",
        "between two rows is a difference between two searches.",
        "",
        "### Controls",
        "",
        "Every score is reported against three nulls, and a representation must clear all",
        "three to be called a result:",
        "",
        "1. **A dimensionality-matched Gaussian noise control.** The representation is",
        "   replaced by noise of identical shape and run through the identical protocol. This",
        "   is not a formality at these dimensionalities: 20115 random features reach a",
        "   precision-recall area of "
        + format(noise_pr("kmer4") or float("nan"), ".4f")
        + ", well above the "
        + format(prevalence, ".4f")
        + " chance level.",
        "2. **A search-capacity null at matched free-parameter count.** One parameter is",
        "   selected here, so the matched null is K equals 1, whose 95th percentile is "
        + format(matched["p95"], ".4f")
        + ".",
        "3. **A label permutation.** Both labels are permuted together inside the protocol,",
        "   20 repeats, so their pairing with each other survives and only their pairing with",
        "   the sequences is broken.",
        "",
        "## Results",
        "",
        "### No protein language model representation survives the controls",
        "",
        "| representation | PR-AUC | 95 percent CI | noise control | permuted p95 | survives |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    ordered = sorted(
        (label for label in results if "classification" in results[label]),
        key=lambda label: -pr(label),
    )
    for label in ordered:
        interval = intervals.get(label, {}).get("classification", {}).get("pr_auc", {})
        permuted = perm_pr(label)
        lines.append(
            "| `"
            + label
            + "` | "
            + format(pr(label), ".4f")
            + " | "
            + (
                format(interval.get("ci_low", float("nan")), ".4f")
                + " to "
                + format(interval.get("ci_high", float("nan")), ".4f")
                if interval
                else "n/a"
            )
            + " | "
            + (format(noise_pr(label), ".4f") if noise_pr(label) is not None else "n/a")
            + " | "
            + (format(permuted, ".4f") if permuted is not None else "not tested")
            + " | "
            + ("**yes**" if label in survivors else "no")
            + " |"
        )

    lines += [
        "",
        "Chance is the positive prevalence, " + format(prevalence, ".4f") + ".",
        "",
        "ESM-2 650M reaches "
        + format(pr("esm2_650M"), ".4f")
        + " against a noise control of "
        + format(noise_pr("esm2_650M") or float("nan"), ".4f")
        + " and a permuted",
        "95th percentile of "
        + format(perm_pr("esm2_650M") or float("nan"), ".4f")
        + ". ESM-2 8M reaches "
        + format(pr("esm2_8M"), ".4f")
        + " against "
        + format(noise_pr("esm2_8M") or float("nan"), ".4f")
        + " and "
        + format(perm_pr("esm2_8M") or float("nan"), ".4f")
        + ".",
        "Both exceed their noise controls and both fail permutation. **Had we reported the",
        "noise control alone, we would have reported two ESM-2 scales as clearing their",
        "nulls.** This is the single most consequential methodological point in the study.",
        "",
        "No representation under either head clears the composite metric: the highest value",
        "observed is "
        + format(best_cls, ".4f")
        + " against the matched search-capacity null of "
        + format(matched["p95"], ".4f")
        + ", every one of",
        "its bootstrap intervals includes zero, and the median minimum resolvable",
        "difference on this panel, "
        + format(mrd["median"], ".4f")
        + ", exceeds every value observed.",
        "",
        "### The one surviving representation is length and lineage, not motif",
        "",
        "A 4-mer frequency block clears all three controls. Its attribution, computed",
        "exactly for the linear head and out of fold, identifies what it has cleared them",
        "with:",
        "",
        "| measurement | value |",
        "| --- | --- |",
        "| out-of-fold score against sequence length | Spearman +0.5212, p 3.23e-05 |",
        "| attribution mass in the top decile of family-explained features | 0.1638, against a 0.1000 feature share |",
        "| per-feature importance against family-explained variance | Spearman +0.2055 |",
        "| attribution mass in the top 1 percent of features | 0.0656, against a 0.0100 feature share |",
        "",
        "The signal is diffuse across 20115 features and systematically aligned with",
        "lineage and length. With 57 rows no individual coefficient is estimable, and no",
        "small set of 4-mers carries the result. We therefore do not interpret the ranking",
        "as motif discovery, and we state the surviving result as what it is: a",
        "length-and-lineage association strong enough to separate actives, reached through",
        "4-mer composition.",
        "",
        "### The representations encode lineage, measured without activity labels",
        "",
        "| what is predicted | ESM-2 650M | best composition control | chance |",
        "| --- | --- | --- | --- |",
        "| evolutionary family, 5-fold accuracy | 0.8197 | 0.6621 | 0.3214 |",
        "| activity out of family, PR-AUC | "
        + format(pr("esm2_650M"), ".4f")
        + " | "
        + format(max(pr(l) for l in results if l not in esm_labels and "classification" in results[l]), ".4f")
        + " | "
        + format(prevalence, ".4f")
        + " |",
        "",
        "Family accuracy rises monotonically with scale: 0.7652 at 8M, 0.7833 at 35M,",
        "0.8030 at 150M, 0.8197 at 650M. Activity prediction does not. The leading",
        "principal component of the 650M embedding tracks sequence length at Spearman",
        "-0.7681.",
        "",
        "### Two discrepancies internal to the source",
        "",
        "The article's text states that 59 enzymes were tested and twenty showed detectable",
        "activity. Its Table S1 lists "
        + str(len(rows))
        + " and marks "
        + str(int(active.sum()))
        + ". Both gaps are internal to the",
        "primary source rather than introduced downstream. For the activity count the",
        "responsible enzyme is identifiable: the Figure S1A caption breaks the actives into",
        "11 retroviral, 2 LTR retrotransposon and 7 bacterial, describes those 11 as",
        "\"closely related to the M-MLV RT\", and separately marks wild-type M-MLV RT as the",
        "PE1 comparator. The text therefore excludes the comparator and the table includes",
        "it. For the row count nothing in the published record names the missing two. We",
        "report the panel as the "
        + str(len(rows))
        + " enzymes Table S1 lists.",
        "",
        "## Discussion",
        "",
        "Two explanations are consistent with these results, and this dataset does not",
        "separate them.",
        "",
        "The first is that mean-pooled ESM-2 embeddings of reverse transcriptase domains",
        "carry lineage and length but little that transfers to cross-family function. The",
        "diagnostics support this directly: the same representation that classifies family",
        "at 0.82 predicts activity at barely above chance, and its dominant axis of",
        "variation is a length axis.",
        "",
        "The second is that the panel is too small and too confounded to detect a real",
        "improvement. With "
        + str(int(active.sum()))
        + " positives, a Kish effective sample size of "
        + format(kish, ".2f")
        + ", "
        + str(len(zero_active))
        + " of "
        + str(len(families))
        + " folds",
        "containing no active enzyme, and a median resolvable difference of "
        + format(mrd["median"], ".4f")
        + ", an",
        "improvement smaller than that would be invisible here.",
        "",
        "These have different consequences. Under the first, scaling the model is the wrong",
        "move and pooling or fine-tuning strategy is the question. Under the second, the",
        "dataset is the bottleneck and no representation study on this panel will resolve",
        "anything. We think the honest reading is that both contribute, and that the",
        "diagnostic evidence for the first is stronger than the benchmark evidence for it,",
        "because the diagnostics do not depend on the small number of positives.",
        "",
        "What we would claim without hedging: **on this panel, a dimensionality-matched",
        "noise control is not a sufficient null.** It passed two ESM-2 scales that label",
        "permutation then rejected. Any small-sample representation benchmark that reports",
        "a random-feature control and stops is under-controlled.",
        "",
        "## Limitations",
        "",
        "| limitation | value |",
        "| --- | --- |",
        "| enzymes | " + str(len(rows)) + " |",
        "| positives | " + str(int(active.sum())) + " |",
        "| Kish effective sample size of the composite metric's weighting | " + format(kish, ".3f") + " |",
        "| families with no active enzyme | "
        + str(len(zero_active))
        + " of "
        + str(len(families))
        + ": "
        + ", ".join(zero_active)
        + " |",
        "| informative folds | "
        + str(len(families) - len(zero_active))
        + " of "
        + str(len(families))
        + " |",
        "| median minimum resolvable difference | " + format(mrd["median"], ".4f") + " |",
        "| continuous label provenance | digitized from Figure S1A, roughly 0.5 percentage point resolution |",
        "| family labels | inherited 7-way; the paper's 14 classes exist only in a rendered tree image |",
        "| remote homology | 4 identity clusters cross a family boundary at 30 percent identity |",
        "| accessions pinned exactly | 27 of 57; the source publishes none |",
        "",
        "Choices that bound the scope rather than the panel: only final-layer mean pooling",
        "was evaluated, with no layer or pooling sweep, because a sweep is a selection",
        "decision that belongs inside a fold; only two model heads were used; and the label",
        "permutation covers "
        + str(len(validation["permutation"]))
        + " of the 12 representations, chosen by a stated rule that",
        "includes the leader of each headline metric and both ends of the model-scale range.",
        "",
        "## Data and code availability",
        "",
        "| item | location |",
        "| --- | --- |",
        "| source workbook | `tasks/taskA_crossfamily/raw/mmc2.xlsx`, with checksums and the full fetch attempt log |",
        "| curated dataset | `tasks/taskA_crossfamily/curated.csv`, SHA256 `" + sha256_of(CURATED) + "` |",
        "| frozen splits | `tasks/taskA_crossfamily/splits/` |",
        "| benchmark results | `bench/results/taskA_representations.json` |",
        "| validation and nulls | `bench/results/taskA_validation.json` |",
        "| reconciliation of the source | `reports/reconciliation.md` |",
        "| full auditable report | `reports/FINAL_REPORT.md` |",
        "",
        "Reproduce with `make taskA` after the data and representation stages. Seed "
        + str(main_results["seed"])
        + " throughout.",
        "",
        "## Reference",
        "",
        "Doman JL, Pandey S, Neugebauer ME, An M, Davis JR, Randolph PB, et al.",
        "Phage-assisted evolution and protein engineering yield compact, efficient prime",
        "editors. Cell. 2023;186(18):3983-4002.e26. DOI 10.1016/j.cell.2023.07.039.",
    ]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("")
    print("survivors: " + str(survivors))
    print("wrote " + OUT.relative_to(REPO_ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
