"""Generate reports/CROSS_TASK_COMPARISON.md.

The piece that makes the repository a study rather than two disconnected benchmarks. Task
A's numbers are read from its result files so they cannot drift from the benchmark that
produced them; Task B's status is read from whether its curated table exists.

    python reports/build_cross_task_comparison.py

Output: reports/CROSS_TASK_COMPARISON.md
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import numpy as np

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from schemas.task_schema import print_run_header, sha256_of  # noqa: E402

CURATED_A = REPO_ROOT / "tasks" / "taskA_crossfamily" / "curated.csv"
CURATED_B = REPO_ROOT / "tasks" / "taskB_mmlv_dms" / "curated.csv"
MAIN_A = REPO_ROOT / "bench" / "results" / "taskA_representations.json"
VALIDATION_A = REPO_ROOT / "bench" / "results" / "taskA_validation.json"
SPLITS_B = REPO_ROOT / "tasks" / "taskB_mmlv_dms" / "splits"
OUT = REPO_ROOT / "reports" / "CROSS_TASK_COMPARISON.md"


def main() -> int:
    print_run_header("reports/build_cross_task_comparison.py", [CURATED_A, MAIN_A])
    main_a = json.loads(MAIN_A.read_text(encoding="utf-8"))
    validation_a = json.loads(VALIDATION_A.read_text(encoding="utf-8"))
    with CURATED_A.open(encoding="utf-8") as handle:
        rows_a = list(csv.DictReader(handle))
    active = np.array([r["active"] == "1" for r in rows_a])
    prevalence = float(active.mean())

    results = main_a["results"]
    noise = validation_a["noise"]
    permutation = validation_a["permutation"]

    def pr(label: str) -> float:
        return results[label]["classification"]["pr_auc"]

    survivors = []
    for label in results:
        if "classification" not in results[label]:
            continue
        noise_pr = noise.get(label, {}).get("classification", {}).get("pr_auc")
        perm_pr = permutation.get(label, {}).get("classification", {}).get("pr_auc_p95")
        if noise_pr is None or perm_pr is None:
            continue
        if pr(label) > max(noise_pr, prevalence, perm_pr):
            survivors.append(label)

    esm = {k: pr(k) for k in results if k.startswith("esm2_") and "classification" in results[k]}
    best_esm = max(esm, key=esm.get)

    task_b_built = CURATED_B.is_file()
    split_files = sorted(p.name for p in SPLITS_B.glob("*.csv"))

    lines = [
        "# Cross-task comparison: what the pair of tasks does and does not establish",
        "",
        "Generated by `reports/build_cross_task_comparison.py`. Task A's numbers are read",
        "from its result files; Task B's status is read from whether its curated table",
        "exists.",
        "",
        "## The rule this document obeys",
        "",
        "**The two tasks' metrics are never numerically compared, and no combined score",
        "appears anywhere in this repository.**",
        "",
        "Task A measures whether a representation transfers across reverse transcriptase",
        "families, scored by precision-recall area over a binary activity call and by a",
        "composite metric on percent precise prime edits. Task B measures whether a",
        "representation predicts the effect of a single substitution within one backbone,",
        "scored by Spearman correlation on a log2 enrichment ratio rescaled to the interval",
        "from -1 to 1.",
        "",
        "Those are different physical quantities, on different scales, with different",
        "chance levels, over different numbers of rows. A sentence of the form",
        "\"representation X scores 0.6 on Task A and 0.4 on Task B\" would be meaningless,",
        "and `schemas/task_schema.py` refuses to concatenate two task tables whose labels",
        "are measured in different units, so the merge is blocked in code and not only in",
        "prose.",
        "",
        "What the pair can support is a **qualitative** contrast: whether the same family of",
        "representations succeeds in one regime and fails in the other. That is a weaker",
        "claim than a numerical comparison and it is the only one available.",
        "",
        "## Where the two tasks stand",
        "",
        "| | Task A, cross-family transfer | Task B, within-protein variant effect |",
        "| --- | --- | --- |",
        "| question | does a representation transfer to an unseen RT family | does a representation predict a single substitution's effect in one backbone |",
        "| source | Doman et al., Cell 2023, Supplementary Table S1 | Li et al., bioRxiv 2026, Supplementary Tables S6 and S7 |",
        "| rows | " + str(len(rows_a)) + " enzymes, " + str(int(active.sum())) + " active | 1045 variants plus wild type, **expected** |",
        "| label | binary activity, plus a percent efficiency | log2 enrichment rescaled to -1 to 1, wild type at 0 |",
        "| primary metric | PR-AUC out of family | Spearman, position-held-out and stretch-held-out |",
        "| data status | **complete and endorsed** through Gate G2 | **blocked at acquisition**; the activity values were never deposited |",
        "| result status | "
        + str(len(results))
        + " representations benchmarked with three nulls each | **no result exists** |",
        "",
        "## What Task A established",
        "",
        "Detail in `reports/FINAL_REPORT.md`. The three findings that bear on the",
        "cross-task question:",
        "",
        "1. **No ESM-2 size survives the controls.** The best, `"
        + best_esm
        + "`, reaches a PR-AUC of "
        + format(esm[best_esm], ".4f")
        + " against a",
        "   positive prevalence of "
        + format(prevalence, ".4f")
        + ". It clears its dimensionality-matched Gaussian noise",
        "   control and then loses to its own shuffled labels.",
        "2. **The only representation surviving all three controls is not a language",
        "   model**: "
        + ", ".join("`" + s + "`" for s in survivors)
        + ". Its signal is strongly associated with sequence length",
        "   and family structure rather than with any specific motif.",
        "3. **The same representations encode lineage strongly.** ESM-2 650M classifies RT",
        "   family at 0.8197 five-fold accuracy against a 0.3214 majority baseline, rising",
        "   monotonically with model scale, and its leading principal component tracks",
        "   sequence length at Spearman -0.7681. Both measured without any activity label.",
        "",
        "## What Task B would have tested, and why it could not",
        "",
        "Task B is the regime where protein language models are expected to work. Masked",
        "marginal likelihood is a standard and often strong zero-shot variant effect",
        "predictor, and the within-protein setting is where the representation's local",
        "sequence context is most informative.",
        "",
        "It is blocked at acquisition. The per-variant activity values were not deposited",
        "with the preprint, which is still at version 1 after three months; no journal",
        "version exists; the publisher's own structured metadata declares zero",
        "supplementary-material blocks; and seven repository searches across Zenodo, Dryad,",
        "OSF and GitHub returned nothing. Detail in `reports/taskB_mmlv_dms/FINAL_REPORT.md`.",
        "",
        "What is ready and waiting: the reference frame resolved and confirmed at seven",
        "residue positions, the 1046 expected variant identifiers derived and frozen, "
        + str(len(split_files))
        + "",
        "split regimes written and verified, and a parser that halts rather than adapts on",
        "any numbering mismatch.",
        "",
        "## The hypothesis the pair was built to bear on",
        "",
        "> Do these representations capture local mutational tolerance within a protein",
        "> while failing at functional transfer across families?",
        "",
        "**This hypothesis is not tested, and this repository does not claim it either way.**",
        "",
        "Task A supplies one half of the contrast, and supplies it with controls: on a",
        "57-enzyme cross-family panel, mean-pooled ESM-2 embeddings do not transfer, and",
        "they demonstrably encode lineage and length instead. The other half, that the same",
        "representations do succeed within a protein, is **assumed from the wider literature",
        "and is not measured here.**",
        "",
        "That distinction matters because the asymmetry is exactly where a plausible story",
        "would outrun the evidence. The tempting sentence is \"protein language models",
        "capture local mutational tolerance but not cross-family function, as the contrast",
        "between our two tasks shows\". That sentence is not available. Only one of the two",
        "tasks produced a measurement.",
        "",
        "### Three reasons a one-sided result cannot carry the hypothesis",
        "",
        "1. **A null result in one regime is not evidence of success in another.** Task A's",
        "   finding is consistent with the hypothesis, and equally consistent with the",
        "   representations carrying little functional signal in either regime.",
        "2. **Task A's own limits are not resolved.** With 21 positives, a Kish effective",
        "   sample size of 11.338, three of seven folds holding no active enzyme, and a",
        "   median resolvable CLS difference larger than every CLS observed, the panel",
        "   cannot distinguish \"the representations carry nothing\" from \"the panel cannot",
        "   detect what they carry\". Those have different consequences for the hypothesis.",
        "3. **The regimes differ in more than locality.** Task B's label is an enrichment",
        "   ratio from a pooled screen; Task A's is a per-enzyme editing percentage from",
        "   individually assayed constructs. A difference in outcome between them would",
        "   confound representation behaviour with assay type, which is the same confound",
        "   that motivated splitting the tasks in the first place.",
        "",
        "## What the repository can claim today",
        "",
        "Stated at the strength the evidence supports, and no further:",
        "",
        "- **Supported, with controls.** On this 57-enzyme cross-family panel, mean-pooled",
        "  ESM-2 embeddings do not improve activity prediction over simpler biological",
        "  representations under family-held-out evaluation, and no ESM-2 size survives a",
        "  label permutation.",
        "- **Supported, without reference to any activity label.** The same embeddings",
        "  encode evolutionary family strongly and sequence length strongly.",
        "- **Supported, and methodological.** On a panel this size a dimensionality-matched",
        "  noise control is not a sufficient null. It passed two ESM-2 scales that label",
        "  permutation then rejected, so a small-sample representation benchmark reporting a",
        "  random-feature control and stopping is under-controlled.",
        "- **Not supported, because not measured.** That these representations succeed at",
        "  within-protein variant effect prediction on this enzyme.",
        "- **Not supported, because untestable here.** The cross-regime contrast itself.",
        "",
        "## What would change this document",
        "",
        "Task B's activity values. With them, the contrast becomes measurable and this",
        "document becomes a comparison rather than a statement of what is missing. Until",
        "then it records a one-sided study honestly, which is better than a two-sided story",
        "with one side imagined.",
        "",
        "| artifact | state |",
        "| --- | --- |",
        "| `tasks/taskA_crossfamily/curated.csv` | present, SHA256 `" + sha256_of(CURATED_A) + "` |",
        "| `tasks/taskB_mmlv_dms/curated.csv` | "
        + ("present" if task_b_built else "**absent**, blocked on the activity values")
        + " |",
        "| Task B frozen splits | " + ", ".join("`" + f + "`" for f in split_files) + " |",
    ]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("")
    print("Task A survivors: " + str(survivors))
    print("Task B curated table present: " + str(task_b_built))
    print("wrote " + OUT.relative_to(REPO_ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
